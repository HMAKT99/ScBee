// Builds the ScBee GitHub Action into packages/pr-action/release/: exactly the files of the public action repo
// (action.yml at the root for the Marketplace, a single bundled dist/index.mjs, README, LICENSE, the screenshot).
// Run `npm run build` first. Usage: node scripts/build-action.mjs [--out <folder>]
import { build } from "esbuild";
import { cpSync, existsSync, mkdirSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), "../packages/pr-action");
const i = process.argv.indexOf("--out");
const out = i > 0 ? resolve(process.argv[i + 1]) : join(pkg, "release");
if (i < 0) rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "dist"), { recursive: true });
await build({
  entryPoints: [join(pkg, "src/index.ts")],
  outfile: join(out, "dist/index.mjs"),
  bundle: true, platform: "node", format: "esm", target: "node22",
  legalComments: "eof",
  banner: { js: "// ScBee GitHub Action. Generated by scripts/build-action.mjs in https://github.com/HMAKT99/ScBee: edit the source there." },
});
for (const f of ["action.yml", "README.md", "LICENSE"]) cpSync(join(pkg, f), join(out, f));
if (existsSync(join(pkg, "docs"))) cpSync(join(pkg, "docs"), join(out, "docs"), { recursive: true });
console.log(`built the action into ${out}`);
